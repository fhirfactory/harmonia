package net.fhirfactory.harmonia.model.core.domain.fhir;

import ca.uhn.fhir.context.FhirContext;
import net.fhirfactory.harmonia.model.core.workflow.tasks.ErgonPayload;
import net.fhirfactory.harmonia.model.core.naming.Topic;
import net.fhirfactory.harmonia.model.core.naming.factory.TopicFactory;
import org.hl7.fhir.instance.model.api.IBaseResource;
import org.hl7.fhir.r5.model.Task;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

@DisplayName("Ergon Task Topic interchange compatibility")
class ErgonTopicInterchangeTest {

    /*
     * Fixtures below are the exact bytes written by the HEAD (predecessor) Topic through the
     * HEAD converter's ObjectMapper, generated by compiling HEAD sources with Jackson 2.17.2.
     */
    private static final String HISTORICAL_TOPIC = "{\"id\":\"123e4567-e89b-12d3-a456-426614174000\","
            + "\"canonicalName\":{\"0\":{\"qualifier\":\"Domain\",\"name\":\"Health\"},"
            + "\"1\":{\"qualifier\":\"Model\",\"name\":\"HL7\"},"
            + "\"2\":{\"qualifier\":\"ModelVersion\",\"name\":\"2.4\"},"
            + "\"3\":{\"qualifier\":\"DataElement\",\"name\":\"ADT\"},"
            + "\"4\":{\"qualifier\":\"DataElementQualifier\",\"name\":\"A01\"}},"
            + "\"name\":\"Health.HL7.2.4.ADT.A01\",\"friendlyName\":\"A01\","
            + "\"relativeName\":\"DataElementQualifier=A01\",\"dataElement\":\"ADT\","
            + "\"dataElementQualifier\":\"A01\",\"depth\":5,\"shortId\":\"123e4567\","
            + "\"domain\":\"Health\",\"model\":\"HL7\",\"modelVersion\":\"2.4\","
            + "\"compositeTrigger\":\"ADT^A01\"}";

    private static final String HISTORICAL_QUALIFIED_TOPIC = "{\"id\":\"123e4567-e89b-12d3-a456-426614174000\","
            + "\"canonicalName\":{\"0\":{\"qualifier\":\"Domain\",\"name\":\"Alpha\"},"
            + "\"1\":{\"qualifier\":\"Role\",\"name\":\"Beta\"}},\"name\":\"Alpha.Beta\","
            + "\"friendlyName\":\"Beta\",\"relativeName\":\"Role=Beta\",\"dataElement\":null,"
            + "\"dataElementQualifier\":null,\"depth\":2,\"shortId\":\"123e4567\","
            + "\"domain\":\"Alpha\",\"model\":\"Beta\",\"modelVersion\":null,\"compositeTrigger\":\"\"}";

    @Test
    @DisplayName("Historical Topic JSON replays with its original qualified identity")
    void historicalJsonRetainsQualifiedIdentity() {
        Topic restored = ErgonPayloadFhirConverter.deserializeTopic(HISTORICAL_TOPIC);

        assertThat(restored.getCanonicalName())
                .isEqualTo("Domain=Health.Model=HL7.ModelVersion=2\\.4.DataElement=ADT.DataElementQualifier=A01");
        assertThat(ErgonPayloadFhirConverter.deserializeTopic(HISTORICAL_QUALIFIED_TOPIC).getCanonicalName())
                .isEqualTo("Domain=Alpha.Role=Beta");
    }

    @Test
    @DisplayName("Inconsistent predecessor projections and the plain-text fallback cannot change identity")
    void historicalProjectionsAreVerified() {
        assertThatThrownBy(() -> ErgonPayloadFhirConverter.deserializeTopic(
                HISTORICAL_TOPIC.replace("\"model\":\"HL7\"", "\"model\":\"FHIR\"")))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> ErgonPayloadFhirConverter.deserializeTopic(
                HISTORICAL_QUALIFIED_TOPIC.replace("\"modelVersion\":null", "\"modelVersion\":\"1\"")))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> ErgonPayloadFhirConverter.deserializeTopic(
                HISTORICAL_TOPIC.replace("\"shortId\":\"123e4567\"", "\"shortId\":\"ffffffff\"")))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> ErgonPayloadFhirConverter.deserializeTopic(
                HISTORICAL_TOPIC.replace("\"compositeTrigger\":\"ADT^A01\"", "\"extra\":1")))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> ErgonPayloadFhirConverter.deserializeTopic(
                HISTORICAL_TOPIC.replace("123e4567-e89b-12d3-a456-426614174000", "not-a-uuid")))
                .isInstanceOf(IllegalArgumentException.class);
        // The predecessor's value-only fallback text is read with historical qualifiers, never N<position>.
        assertThat(ErgonPayloadFhirConverter.deserializeTopic("Alpha.Beta").getCanonicalName())
                .isEqualTo("Domain=Alpha.Model=Beta");
    }

    @Test
    @DisplayName("Current JSON retains ordered versions and explicit qualifiers")
    void currentJsonRetainsVersionsAndQualifiers() {
        Topic topic = Topic.builder().addEntry("Role", "LAB", "2.4")
                .addEntry("N1", "leaf").build();

        Topic restored = ErgonPayloadFhirConverter.deserializeTopic(
                ErgonPayloadFhirConverter.serializeTopic(topic));

        assertThat(restored.getCanonicalNameWithVersion()).isEqualTo(topic.getCanonicalNameWithVersion());
        assertThat(restored.getEntries().getFirst().getVersion()).contains("2.4");
    }

    @Test
    @DisplayName("Plain historical names retain standard qualifiers and numeric version collapse")
    void plainTextUsesHistoricalNameRules() {
        Topic restored = ErgonPayloadFhirConverter.deserializeTopic("Health.HL7.2.4.ADT.A01");

        assertThat(restored.getCanonicalName())
                .isEqualTo("Domain=Health.Model=HL7.ModelVersion=2\\.4.DataElement=ADT.DataElementQualifier=A01");
        assertThat(ErgonPayloadFhirConverter.deserializeTopic("Domain=Alpha.Model=FHIR"))
                .isEqualTo(TopicFactory.fromName("Domain=Alpha.Model=FHIR"));
    }

    @Test
    @DisplayName("Malformed JSON-looking or ambiguous text is rejected rather than reparsed as a name")
    void malformedAndAmbiguousRepresentationsFailClosed() {
        assertThatThrownBy(() -> ErgonPayloadFhirConverter.deserializeTopic("{"))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> ErgonPayloadFhirConverter.deserializeTopic("Domain=Alpha\\"))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> ErgonPayloadFhirConverter.deserializeTopic("Alpha..Beta"))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> ErgonPayloadFhirConverter.deserializeTopic("{\"entries\":[],\"entries\":[]}"))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> ErgonPayloadFhirConverter.deserializeTopic(
                HISTORICAL_TOPIC.replace("\"name\":\"Health.HL7.2.4.ADT.A01\"", "\"name\":\"wrong\"")))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> ErgonPayloadFhirConverter.deserializeTopic(
                HISTORICAL_TOPIC.replace("\"depth\":5", "\"depth\":4")))
                .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    @DisplayName("Versioned Topic strings survive the governed FHIR Task XML extension boundary")
    void fhirTaskXmlRoundTripPreservesTopicVersion() {
        Topic topic = Topic.builder().addEntry("Domain", "Health", "2.4")
                .addEntry("Model", "FHIR").build();
        ErgonPayload payload = new ErgonPayload(7, topic, topic, (IBaseResource) null);
        Task task = new Task();
        task.addInput(ErgonPayloadFhirConverter.toTaskInput(payload));
        FhirContext context = FhirContext.forR5();

        String xml = context.newXmlParser().encodeResourceToString(task);
        Task restoredTask = context.newXmlParser().parseResource(Task.class, xml);
        ErgonPayload restored = ErgonPayloadFhirConverter.fromTaskInput(restoredTask.getInputFirstRep());

        assertThat(restored.getPayloadContainer().getCanonicalNameWithVersion())
                .isEqualTo(topic.getCanonicalNameWithVersion());
        assertThat(restored.getPayloadContainer().getEntries().getFirst().getVersion()).contains("2.4");
    }
}