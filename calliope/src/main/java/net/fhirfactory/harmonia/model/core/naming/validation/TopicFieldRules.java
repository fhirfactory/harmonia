package net.fhirfactory.harmonia.model.core.naming.validation;

import net.fhirfactory.harmonia.model.core.naming.valuesets.NamingFailureCategory;
import net.fhirfactory.harmonia.model.core.naming.valuesets.NamingFieldKind;
import net.fhirfactory.harmonia.model.core.naming.valuesets.NamingOperation;

/**
 * Shared Unicode and completed-field validation for the Naming boundary.
 *
 * <p>These checks are intentionally centralized so builders, canonical
 * parsers, and interchange adapters enforce identical field semantics while
 * exposing only safe failure categories. Violations are raised as
 * {@link NamingRuleViolation} and translated by the Naming model boundary.</p>
 *
 * <p>This type is implementation machinery of the Naming component and is not
 * part of the supported Naming API.</p>
 */
public final class TopicFieldRules {

    /** Prevents construction of this stateless validation utility. */
    private TopicFieldRules() {
        throw new AssertionError("No instances");
    }

    /**
     * Counts well-formed Unicode code points and rejects malformed surrogate sequences.
     *
     * @param value text to measure
     * @param operation operation used for failure metadata
     * @param field field kind used for failure metadata
     * @param index entry position used for failure metadata, or {@code null}
     * @param nullCategory category reported when {@code value} is {@code null}
     * @return the number of code points
     * @throws NamingRuleViolation when the value is absent or contains an unpaired surrogate
     */
    public static int codePointCount(
            String value,
            NamingOperation operation,
            NamingFieldKind field,
            Integer index,
            NamingFailureCategory nullCategory) {
        if (value == null) {
            throw new NamingRuleViolation(nullCategory, operation, field, index);
        }
        int count = 0;
        for (int offset = 0; offset < value.length();) {
            char current = value.charAt(offset);
            if (Character.isHighSurrogate(current)) {
                if (offset + 1 >= value.length() || !Character.isLowSurrogate(value.charAt(offset + 1))) {
                    throw new NamingRuleViolation(NamingFailureCategory.INVALID_FIELD, operation, field, index);
                }
                offset += 2;
            } else if (Character.isLowSurrogate(current)) {
                throw new NamingRuleViolation(NamingFailureCategory.INVALID_FIELD, operation, field, index);
            } else {
                offset++;
            }
            count++;
        }
        return count;
    }

    /**
     * Validates a supplied printable-ASCII qualifier or permits assembly-time generation.
     *
     * @param qualifier qualifier to validate; {@code null} or empty only when generation is allowed
     * @param allowGenerated whether a missing qualifier will be generated by builder assembly
     * @param operation operation used for failure metadata
     * @param index entry position used for failure metadata, or {@code null}
     * @throws NamingRuleViolation when the qualifier is missing, oversized or not printable ASCII
     */
    public static void validateQualifierInput(
            String qualifier,
            boolean allowGenerated,
            NamingOperation operation,
            Integer index) {
        if (qualifier == null || qualifier.isEmpty()) {
            if (allowGenerated) {
                return;
            }
            throw new NamingRuleViolation(qualifier == null ? NamingFailureCategory.MISSING_INPUT
                    : NamingFailureCategory.INVALID_FIELD, operation, NamingFieldKind.QUALIFIER, index);
        }
        validateAsciiField(qualifier, NamingFieldKind.QUALIFIER,
                NamingLimits.MAX_QUALIFIER_CODE_POINTS, operation, index);
    }

    /**
     * Enforces the accepted Unicode categories, boundary-space rule, and value length.
     *
     * @param value Topic value to validate
     * @param operation operation used for failure metadata
     * @param index entry position used for failure metadata, or {@code null}
     * @throws NamingRuleViolation when the value is missing, empty, oversized or contains a rejected character
     */
    public static void validateValue(String value, NamingOperation operation, Integer index) {
        int count = codePointCount(value, operation, NamingFieldKind.VALUE, index,
                NamingFailureCategory.MISSING_INPUT);
        if (count == 0) {
            throw new NamingRuleViolation(NamingFailureCategory.INVALID_FIELD, operation, NamingFieldKind.VALUE, index);
        }
        checkLimit(count, NamingLimits.MAX_VALUE_CODE_POINTS, operation, NamingFieldKind.VALUE, index);
        if (Character.isWhitespace(value.codePointAt(0))
                || Character.isWhitespace(value.codePointBefore(value.length()))) {
            throw new NamingRuleViolation(NamingFailureCategory.INVALID_FIELD, operation, NamingFieldKind.VALUE, index);
        }
        for (int offset = 0; offset < value.length();) {
            int codePoint = value.codePointAt(offset);
            offset += Character.charCount(codePoint);
            if (codePoint == ' ') {
                continue;
            }
            int type = Character.getType(codePoint);
            if (type != Character.UPPERCASE_LETTER
                    && type != Character.LOWERCASE_LETTER
                    && type != Character.TITLECASE_LETTER
                    && type != Character.MODIFIER_LETTER
                    && type != Character.OTHER_LETTER
                    && type != Character.DECIMAL_DIGIT_NUMBER
                    && type != Character.LETTER_NUMBER
                    && type != Character.OTHER_NUMBER
                    && type != Character.CONNECTOR_PUNCTUATION
                    && type != Character.DASH_PUNCTUATION
                    && type != Character.START_PUNCTUATION
                    && type != Character.END_PUNCTUATION
                    && type != Character.INITIAL_QUOTE_PUNCTUATION
                    && type != Character.FINAL_QUOTE_PUNCTUATION
                    && type != Character.OTHER_PUNCTUATION
                    && type != Character.MATH_SYMBOL
                    && type != Character.CURRENCY_SYMBOL
                    && type != Character.MODIFIER_SYMBOL
                    && type != Character.OTHER_SYMBOL
                    && type != Character.NON_SPACING_MARK
                    && type != Character.COMBINING_SPACING_MARK
                    && type != Character.ENCLOSING_MARK) {
                throw new NamingRuleViolation(NamingFailureCategory.INVALID_FIELD, operation, NamingFieldKind.VALUE, index);
            }
        }
    }

    /**
     * Normalizes builder {@code null}/empty version input to absence and validates present values.
     *
     * @param version supplied version, possibly {@code null} or empty
     * @param operation operation used for failure metadata
     * @param index entry position used for failure metadata, or {@code null}
     * @return the unchanged present version, or {@code null} for absence
     * @throws NamingRuleViolation when a present version is oversized or not printable ASCII
     */
    public static String normalizeVersion(String version, NamingOperation operation, Integer index) {
        if (version == null || version.isEmpty()) {
            return null;
        }
        validateAsciiField(version, NamingFieldKind.VERSION,
                NamingLimits.MAX_VERSION_CODE_POINTS, operation, index);
        return version;
    }

    /**
     * Validates a fully assembled Topic entry without generating or normalizing fields.
     *
     * @param qualifier completed qualifier
     * @param value completed value
     * @param version present version, or {@code null} when absent; an empty version is rejected
     * @param operation operation used for failure metadata
     * @param index entry position used for failure metadata, or {@code null}
     * @throws NamingRuleViolation when any completed field is invalid
     */
    public static void validateTopicCompletedFields(
            String qualifier,
            String value,
            String version,
            NamingOperation operation,
            Integer index) {
        validateQualifierInput(qualifier, false, operation, index);
        validateValue(value, operation, index);
        if (version != null) {
            validateAsciiField(version, NamingFieldKind.VERSION,
                    NamingLimits.MAX_VERSION_CODE_POINTS, operation, index);
        }
    }

    /**
     * Validates exact-text version data while attributing errors to a mask constraint.
     *
     * @param version exact version text after any leading escape has been removed
     * @param operation operation used for failure metadata
     * @param index entry position used for failure metadata, or {@code null}
     * @throws NamingRuleViolation when the text is empty, oversized or not printable ASCII
     */
    public static void validateConstraintVersion(
            String version,
            NamingOperation operation,
            Integer index) {
        validateAsciiField(version, NamingFieldKind.VERSION_CONSTRAINT,
                NamingLimits.MAX_VERSION_CODE_POINTS, operation, index);
    }

    /**
     * Raises a safe category when a measured quantity exceeds its accepted bound.
     *
     * @param count measured quantity
     * @param maximum inclusive accepted maximum
     * @param operation operation used for failure metadata
     * @param field field kind used for failure metadata
     * @param index entry position used for failure metadata, or {@code null}
     * @throws NamingRuleViolation when {@code count} exceeds {@code maximum}
     */
    public static void checkLimit(
            int count,
            int maximum,
            NamingOperation operation,
            NamingFieldKind field,
            Integer index) {
        if (count > maximum) {
            throw new NamingRuleViolation(NamingFailureCategory.LIMIT_EXCEEDED, operation, field, index);
        }
    }

    /**
     * Validates nonempty printable ASCII and rejects leading or trailing spaces.
     *
     * @param value field text
     * @param field field kind used for failure metadata
     * @param maximum inclusive maximum length in code points
     * @param operation operation used for failure metadata
     * @param index entry position used for failure metadata, or {@code null}
     * @throws NamingRuleViolation when the field is missing, empty, oversized, space-bounded or not printable ASCII
     */
    public static void validateAsciiField(
            String value,
            NamingFieldKind field,
            int maximum,
            NamingOperation operation,
            Integer index) {
        int count = codePointCount(value, operation, field, index,
                NamingFailureCategory.MISSING_INPUT);
        if (count == 0) {
            throw new NamingRuleViolation(NamingFailureCategory.INVALID_FIELD, operation, field, index);
        }
        checkLimit(count, maximum, operation, field, index);
        if (value.charAt(0) == ' ' || value.charAt(value.length() - 1) == ' ') {
            throw new NamingRuleViolation(NamingFailureCategory.INVALID_FIELD, operation, field, index);
        }
        for (int offset = 0; offset < value.length(); offset++) {
            char current = value.charAt(offset);
            if (current < 0x20 || current > 0x7e) {
                throw new NamingRuleViolation(NamingFailureCategory.INVALID_FIELD, operation, field, index);
            }
        }
    }
}