package net.fhirfactory.harmonia.model.ergon;

import org.apache.commons.lang3.StringUtils;
import org.hl7.fhir.r5.model.CodeableConcept;
import org.hl7.fhir.r5.model.CodeableReference;
import org.hl7.fhir.r5.model.Coding;
import org.hl7.fhir.r5.model.Task;

import java.util.Arrays;
import java.util.Optional;

/**
 * Enumeration of standard HIE Task Reason categories and codes.
 * <p>
 * <b>Pragma — Task Instance/State</b>: This particular piece of work as it currently exists - will be used
 * wherever Task (as a synthetic FHIR::Task resource) is used within the codebase.
 * <p>
 * Provides mapping to FHIR R5 {@link CodeableConcept} and {@link CodeableReference} structures.
 */
public enum ErgonReasonEnum {

    HARMONIA_SYNTHETIC_TASK(
            "Harmonia-Synthetic-Task",
            "Harmonia-Synthetic-Task",
            "Synthetic task generated by Harmonia gateway or workflow automation"
    ),
    HARMONIA_ADMINISTRATION_TASK(
            "Harmonia-Administration-Task",
            "Harmonia-Administration-Task",
            "Administrative or operational task within the Harmonia platform"
    ),
    HARMONIA_APPROVAL_TASK(
            "Harmonia-Approval-Task",
            "Harmonia-Approval-Task",
            "Task requiring clinical, administrative, or compliance approval"
    ),
    HARMONIA_INFORMATION_REQUEST_TASK(
            "Harmonia-InformationRequest-Task",
            "Harmonia-InformationRequest-Task",
            "Task requesting additional patient, encounter, or clinical information"
    );

    public static final String TASK_REASON_SYSTEM = "http://fhirfactory.net/harmonia/task-reason";
    public static final String LEGACY_TASK_REASON_SYSTEM = "http://fhirfactory.net/hie/task-reason";

    // Legacy aliases for backwards compatibility
    public static final ErgonReasonEnum HIE_SYNTHETIC_TASK = HARMONIA_SYNTHETIC_TASK;
    public static final ErgonReasonEnum HIE_ADMINISTRATION_TASK = HARMONIA_ADMINISTRATION_TASK;
    public static final ErgonReasonEnum HIE_APPROVAL_TASK = HARMONIA_APPROVAL_TASK;
    public static final ErgonReasonEnum HIE_INFORMATION_REQUEST_TASK = HARMONIA_INFORMATION_REQUEST_TASK;

    private final String code;
    private final String display;
    private final String description;

    ErgonReasonEnum(String code, String display, String description) {
        this.code = code;
        this.display = display;
        this.description = description;
    }

    public String getCode() {
        return code;
    }

    public String getDisplay() {
        return display;
    }

    public String getDescription() {
        return description;
    }

    public String getSystem() {
        return TASK_REASON_SYSTEM;
    }

    /**
     * Converts this Harmonia task reason into a FHIR R5 {@link CodeableConcept}.
     *
     * @return populated {@link CodeableConcept} with Harmonia coding system and text
     */
    public CodeableConcept toCodeableConcept() {
        CodeableConcept concept = new CodeableConcept();
        concept.setText(code);
        Coding coding = concept.addCoding();
        coding.setSystem(TASK_REASON_SYSTEM);
        coding.setCode(code);
        coding.setDisplay(display);
        return concept;
    }

    /**
     * Converts this Harmonia task reason into a FHIR R5 {@link CodeableReference}.
     *
     * @return populated {@link CodeableReference} containing the concept
     */
    public CodeableReference toCodeableReference() {
        CodeableReference reference = new CodeableReference();
        reference.setConcept(toCodeableConcept());
        return reference;
    }

    /**
     * Applies this reason to the given FHIR R5 {@link Task} resource.
     * Adds the reason entry on the Task if not already present.
     *
     * @param task the FHIR Task resource to update
     * @return the updated Task resource
     */
    public Task applyTo(Task task) {
        if (task != null) {
            boolean alreadyPresent = task.hasReason() && task.getReason().stream().anyMatch(r ->
                    r.hasConcept() && (
                            code.equalsIgnoreCase(r.getConcept().getText()) ||
                            (r.getConcept().hasCoding() && r.getConcept().getCoding().stream().anyMatch(c -> code.equalsIgnoreCase(c.getCode())))
                    )
            );
            if (!alreadyPresent) {
                task.addReason(toCodeableReference());
            }
        }
        return task;
    }

    /**
     * Finds a {@link ErgonReasonEnum} by its string code, display, or enum name.
     *
     * @param code text code, display name, or enum name
     * @return optional containing the matching enum if found
     */
    public static Optional<ErgonReasonEnum> fromCode(String code) {
        if (StringUtils.isBlank(code)) {
            return Optional.empty();
        }
        String clean = code.trim();
        if (clean.equalsIgnoreCase("HIE-Synthetic-Task") || clean.equalsIgnoreCase("hie_synthetic_task") || clean.equalsIgnoreCase("HIE_SYNTHETIC_TASK")) {
            return Optional.of(HARMONIA_SYNTHETIC_TASK);
        }
        if (clean.equalsIgnoreCase("HIE-Administration-Task") || clean.equalsIgnoreCase("hie_administration_task") || clean.equalsIgnoreCase("HIE_ADMINISTRATION_TASK")) {
            return Optional.of(HARMONIA_ADMINISTRATION_TASK);
        }
        if (clean.equalsIgnoreCase("HIE-Approval-Task") || clean.equalsIgnoreCase("hie_approval_task") || clean.equalsIgnoreCase("HIE_APPROVAL_TASK")) {
            return Optional.of(HARMONIA_APPROVAL_TASK);
        }
        if (clean.equalsIgnoreCase("HIE-InformationRequest-Task") || clean.equalsIgnoreCase("hie_information_request_task") || clean.equalsIgnoreCase("HIE_INFORMATION_REQUEST_TASK")) {
            return Optional.of(HARMONIA_INFORMATION_REQUEST_TASK);
        }
        return Arrays.stream(values())
                .filter(r -> r.code.equalsIgnoreCase(clean)
                        || r.display.equalsIgnoreCase(clean)
                        || r.name().equalsIgnoreCase(clean)
                        || r.name().replace("_", "-").equalsIgnoreCase(clean))
                .findFirst();
    }

    /**
     * Checks if a FHIR R5 {@link Task} has a reason matching the given code.
     *
     * @param task the Task to check
     * @param reason the reason to check for
     * @return true if the Task has the specified reason
     */
    public static boolean hasReason(Task task, ErgonReasonEnum reason) {
        if (task == null || reason == null || !task.hasReason()) {
            return false;
        }
        String legacyCode = reason.code.replace("Harmonia-", "HIE-");
        return task.getReason().stream().anyMatch(r -> {
            if (!r.hasConcept()) {
                return false;
            }
            CodeableConcept concept = r.getConcept();
            if (reason.code.equalsIgnoreCase(concept.getText()) || legacyCode.equalsIgnoreCase(concept.getText())) {
                return true;
            }
            if (concept.hasCoding()) {
                return concept.getCoding().stream()
                        .anyMatch(c -> reason.code.equalsIgnoreCase(c.getCode()) || legacyCode.equalsIgnoreCase(c.getCode()));
            }
            return false;
        });
    }

    /**
     * Helper to ensure the default Harmonia synthetic task reason is set on a Task if not already present.
     *
     * @param task the Task resource to check and update
     * @return the updated Task
     */
    public static Task ensureSyntheticTaskReason(Task task) {
        if (task != null) {
            if (!task.hasReason() || task.getReason().isEmpty()) {
                HARMONIA_SYNTHETIC_TASK.applyTo(task);
            }
        }
        return task;
    }

    @Override
    public String toString() {
        return code;
    }
}
