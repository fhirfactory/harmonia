"""Generate/check the root review manifest from canonical continuum elements.

This is a navigation projection, never an element input or architectural authority.
The canonical navigation tree supplies architecture hierarchy and coordinates.
"""
import argparse
from collections import Counter
import html
import json
from pathlib import Path
import re
import sys

import architecture_continuum as c
import continuum_navigation as nav
import os


def cell(value):
    """Render source text literally inside a Markdown table, including newlines."""
    if not isinstance(value, str):
        value = json.dumps(value, ensure_ascii=False, sort_keys=True)
    value = html.escape(value, quote=True)
    # Entities prevent Markdown formatting, table delimiters and injected links.
    value = re.sub(r'[\\`*_|\[\]{}]', lambda m: f'&#{ord(m[0])};', value)
    return '<br>'.join(value.splitlines())


def qualifications(metadata):
    parts = [cell('standing.' + key + ': ') + cell(value)
             for key, value in sorted(metadata['standing'].items())
             if key not in ('semantic', 'currentness')]
    parts += [cell('Unresolved ' + key + ': ') + cell(value)
              for key, value in sorted(metadata.get('unresolvedProperties', {}).items())]
    if metadata.get('sourceUnresolved'):
        parts.append('sourceUnresolved: ' + cell(metadata['sourceUnresolved']))
    return '<br>'.join(parts) or 'None recorded'


def render(root=c.ROOT):
    c.validate(root)
    catalogue, elements = c.load(root)
    version = c.read_json(root / 'architecture-release.json')['version']
    tree = nav.load(root, elements)
    locations = nav.by_element(tree)
    currentness = Counter(m['standing']['currentness'] for m, _, _ in elements.values())
    lines = [
        '<!-- Generated by enterprise-architecture/tooling/continuum_manifest.py. Do not edit. -->', '',
        f'# Harmonia Architecture Continuum — RAD {version}', '',
        'Canonical elements supply architectural meaning and immutable identity.',
        '[navigation.json](navigation.json) supplies the governed architectural organisation.',
        'This derived Manifest supplies navigation and a qualified catalogue; it confers no acceptance.', '',
        f'**{len(elements):,} elements; {len(locations):,} numbered element locations.**', '',
        'Currentness: ' + '; '.join(f'{cell(key)}: {count:,}' for key, count in sorted(currentness.items())) + '.', '',
        'Canonical ID identifies an element; its name supplies meaning; its number is a mutable location.',
        'Hierarchy asserts no semantic containment. Native types, relationships and independent standing',
        'remain in the canonical records. Context references link to Strategy without duplicating capabilities.',
        'The R reference area holds the Stakeholder Index and historical Capability identities outside',
        'the architectural decomposition. Contextual occurrences explicitly link to canonical identities.', '',
        '## Architectural navigation', '',
    ]
    def outline(node, depth):
        cid = node.get('canonicalId')
        text = cell(nav.title(node))
        if cid:
            target = elements[cid][2].relative_to(root / c.CONTINUUM).as_posix()
        elif node.get('source'):
            source, marker, fragment = node['source'].partition('#')
            target = os.path.relpath(root / source, root / c.CONTINUUM) + (marker + fragment if marker else '')
        else:
            target = '#nav-' + node['number'].replace('.', '-')
        lines.append('  ' * depth + '- [' + text + '](' + target + ')')
        for role, reference in nav.references(node):
            lines.append('  ' * (depth + 1) + '- ' + role + ': [' + cell(reference['number'] + ' ' + reference['title'])
                         + '](#element-' + reference['canonicalId'] + '); Canonical ID: ' + reference['canonicalId'])
        for child in node.get('children', []):
            outline(child, depth + 1)
    for part in tree:
        outline(part, 0)
    for part in tree:
        lines += ['', '<a id="nav-' + part['number'] + '"></a>', '## ' + cell(nav.title(part)), '']
        if part.get('description'):
            lines += [part['description'], '']
        # Anchor every organisational node, including nodes deeper than Markdown's
        # heading syntax permits. Coordinates preserve the full depth explicitly.
        for node in list(nav.walk([part]))[1:]:
            if node.get('canonicalId'):
                continue
            lines += ['<a id="nav-' + node['number'].replace('.', '-') + '"></a>',
                      '**' + cell(nav.title(node)) + '**', '']
            if node.get('description'):
                lines += [node['description'], '']
            for role, reference in nav.references(node):
                lines += [role + ': [' + cell(reference['number'] + ' ' + reference['title'])
                          + '](#element-' + reference['canonicalId'] + '); Canonical ID: ' + reference['canonicalId'], '']
            if node.get('relationshipIds'):
                lines += ['Existing canonical associations: ' + ', '.join(node['relationshipIds']), '']
            if node.get('relatedCanonicalIds'):
                lines += ['; '.join('[' + cell(locations[cid]['number'] + ' ' + elements[cid][0]['displayName']) + '](#element-' + cid + ')' for cid in node['relatedCanonicalIds']), '']
        ids = nav.descendants(part)
        if not ids:
            continue
        lines += ['| Navigation | displayName | ArchiMate native type | Harmonia specialisation | Standing / currentness | canonicalName | Canonical ID | Canonical element path | Qualifications / unresolved values |',
                  '| --- | --- | --- | --- | --- | --- | --- | --- | --- |']
        for cid in ids:
            m, _, path = elements[cid]
            relative = path.relative_to(root / c.CONTINUUM).as_posix()
            values = [cell(locations[cid]['number']), cell(m['displayName']), cell(m['archimateType']), cell(m.get('specialization') or '—'),
                      'Semantic: ' + cell(m['standing']['semantic']) + '<br>Currentness: ' + cell(m['standing']['currentness']),
                      cell(m['canonicalName']) if m['canonicalName'] is not None else '**Unresolved**',
                      '<a id="element-' + cid + '"></a>' + cell(cid), f'[{cell(relative)}]({relative})', qualifications(m)]
            if locations[cid].get('classificationIssue'):
                values[-1] += '<br>Classification: ' + cell(locations[cid]['classificationIssue'])
            for role, reference in nav.references(locations[cid]):
                values[-1] += '<br>' + cell(role) + ': [' + cell(reference['number'] + ' ' + reference['title']) + '](#element-' + reference['canonicalId'] + ')'
            lines.append('| ' + ' | '.join(values) + ' |')
    return ('\n'.join(lines).rstrip() + '\n').encode('utf-8')


def publish(root=c.ROOT, *, check=False):
    content = render(root)
    path = root / c.MANIFEST
    if check:
        c.require(path.exists() and path.read_bytes() == content, 'Missing/stale continuum manifest: ' + str(path))
    else:
        path.write_bytes(content)
    return {'status': 'PASS', 'manifest': c.MANIFEST.as_posix(), 'check': check, 'sha256': c.sha(content)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=c.ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        print(json.dumps(publish(args.root, check=args.check)))
        return 0
    except (c.ContinuumError, ValueError, KeyError, OSError) as error:
        print('FAIL: ' + str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
