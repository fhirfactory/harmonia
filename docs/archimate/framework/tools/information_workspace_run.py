"""Run-002: frozen IA naming plus deterministic workspace projection, no release.

Generate once; --check reproduces every generated byte without writing. The main
candidate is plain Exchange XML. Run-001 machinery and evidence remain intact.
"""
import argparse
import copy
import gzip
import json
from pathlib import Path
import sys

import information_naming_run as naming_run
import workspace_navigation as navigation
import containment
import workspace_policy
import run_evidence

g = naming_run.g
ROOT = naming_run.ROOT
RUNS = naming_run.RUNS
RUN = 'run-002'


def fingerprints(paths):
    return {str(path.relative_to(ROOT)): naming_run.sha(path.read_bytes()) for path in sorted(set(paths))}


def frozen_paths():
    paths = [ROOT / 'architecture-release.json', naming_run.INPUTS,
             ROOT / '.junie/reports/2026-10-20-information-architecture-machinery-run-001-naming.md']
    for folder in (RUNS / 'run-001', ROOT / 'docs/archimate/exchange/publish/1.0.10',
                   ROOT / 'docs/archimate/exchange/ingest/1.0.10'):
        paths.extend(path for path in folder.rglob('*') if path.is_file())
    return paths


def build():
    frozen = fingerprints(frozen_paths())
    fixtures, models = naming_run.load_inputs()
    release = (ROOT / 'architecture-release.json').read_bytes()
    g.require(json.loads(release) == dict(version='1.0.10', previous_version='1.0.9'),
              'Run-002 requires unchanged RAD-1.0.10 authority')
    incoming = models['incoming']
    resolved = containment.resolve(incoming.root)
    proposal = naming_run.naming.propose(incoming, resolved=resolved)
    review = naming_run.change_review.review(models['baseline'], incoming, models['control'])
    run001 = RUNS / 'run-001'
    prior_verification = json.loads((run001 / 'verification.json').read_bytes())
    prior_plain = (run001 / 'candidate.xml').read_bytes()
    g.require(naming_run.sha(prior_plain) == prior_verification['candidate_xml_sha256'], 'Frozen Run-001 candidate hash mismatch')
    g.require(gzip.decompress((run001 / 'candidate.xml.gz').read_bytes()) == prior_plain, 'Run-001 plain/archive mismatch')
    g.require((run001 / 'proposed-metadata.json').read_bytes() == naming_run.encoded(proposal), 'Run-001 naming behaviour changed')
    rebindings = naming_run.encoded(review['representation_rebindings'])
    g.require((run001 / 'representation-rebindings.json').read_bytes() == rebindings and
              len(review['representation_rebindings']) == 38, 'Run-001 rebinding evidence changed')
    named = naming_run.candidate(incoming, proposal, RUN)
    named_root = g.ET.fromstring(named)
    naming_checks = naming_run.verify_candidate(incoming, named, proposal, RUN)
    # Apart from candidate standing, the pre-navigation tree must reproduce Run-001.
    prior_root = g.ET.fromstring(prior_plain)
    naming_run.set_property(prior_root, prior_root, naming_run.MARKER,
                            RUN + ': PROPOSED; NOT ACCEPTED; NOT A RAD RELEASE')
    g.require(g.signature(prior_root) == g.signature(g.ET.fromstring(named)), 'Run-001 protected behaviour changed')
    records, collection_sources = workspace_policy.load_records()
    placements = workspace_policy.placements(incoming, resolved, records)
    root, plan = navigation.project(incoming, named_root, resolved=resolved, placements=placements)
    plan['collection_sources_sha256'] = collection_sources
    content = g.serialize(root)
    parsed = g.ET.fromstring(content)
    g.load_schema(g.BASE / 'schemas/archimate3_Diagram.xsd').assertValid(parsed)
    g.validate_identifiers(parsed)
    # Source hashes annotate the run plan; the projector verifies its own plan.
    projection_plan = {key: value for key, value in plan.items() if key != 'collection_sources_sha256'}
    workspace_checks = navigation.verify(incoming, named_root, parsed, projection_plan,
                                        resolved=resolved, placements=placements)
    generation_proof = navigation.prove_generation(incoming, named_root, parsed, placements, resolved)
    # Reverse only navigation, then use the established independent naming
    # allowlist verifier against the original architect submission.
    restored = copy.deepcopy(parsed)
    restored.replace(restored.find('a:organizations', g.N), copy.deepcopy(incoming.root.find('a:organizations', g.N)))
    naming_run.verify_candidate(incoming, g.serialize(restored), proposal, RUN)
    outputs = {
        'candidate.xml': content,
        'resolved-containment.json': naming_run.encoded(resolved.evidence()),
        'proposed-metadata.json': naming_run.encoded(proposal),
        'representation-rebindings.json': rebindings,
        'workspace-projection.json': naming_run.encoded(plan),
        'element-generation-proof.json': naming_run.encoded(generation_proof),
        'verification.json': naming_run.encoded(dict(status='PASS', naming_preservation=naming_checks,
            workspace=workspace_checks, containment=dict(policy=containment.VERSION,
                current_ambiguities=resolved.findings(), excluded_historical=len(resolved.population['excluded'])),
            population=review['population'], naming=proposal['summary'],
            navigation=plan['summary'], element_generation_proof=generation_proof,
            collection_sources_sha256=collection_sources, candidate_xml_sha256=naming_run.sha(content),
            candidate_standing='PROPOSED_NOT_ACCEPTED', canonical_ids_allocated=0,
            semantic_changes=0, documentation='UNCHANGED_CLEANUP_DEFERRED',
            archi_import='PENDING_SOLUTION_ARCHITECT_INSPECTION', archi_roundtrip='NOT_PERFORMED',
            architect_acceptance='NOT_RECORDED', release_created=False)),
    }
    # Freeze the actual machinery, tests, schemas and applicable governance for
    # independent replay. These are byte snapshots, not new authority or releases.
    sources = [*Path(__file__).parent.glob('*.py'),
               *g.BASE.joinpath('schemas').glob('*'),
               *g.BASE.joinpath('tests').glob('test_*naming*.py'),
               g.BASE / 'tests/test_workspace_navigation.py', g.BASE / 'tests/test_containment.py',
               g.BASE / 'tests/test_home_context.py', g.BASE / 'tests/test_home_relationships.py',
               g.BASE / 'tests/test_view_presentation.py', g.BASE / 'README.md',
               *g.BASE.joinpath('tests').glob('test_*praxis*.py'),
               g.BASE / 'tests/test_run_evidence.py', g.BASE / 'tests/test_workspace_policy.py',
               g.BASE / 'governance-transitions.json',
               ROOT / 'AGENTS.md', ROOT / 'docs/AGENTS.md',
               RUNS / RUN / 'validation/reproduce_candidate.py',
               ROOT / 'scripts/architecture_release.py',
               *(ROOT / 'docs/markdown/governance' / name for name in (
                   'architectural-axioms.md', 'canonical-identity-and-naming.md', 'architecture-release-policy.md',
                   'architecture-modelling-strategy.md', 'archimate-ingestion-publication-semantics.md',
                   'archi-navigation-and-view-convention.md', 'archimate-round-trip-engineering-praxis.md',
                   'archimate-ingestion-change-review.md', 'architecture-authoring-praxis.md', 'README.md')),
               *(ROOT / path for path in collection_sources)]
    sources = sorted(set(path for path in sources if path.is_file()))
    transitions = json.loads((g.BASE / 'governance-transitions.json').read_bytes())
    for entry in transitions['transitions']:
        manifest_path = ROOT / entry['manifest']
        sources.append(manifest_path)
        for row in json.loads(manifest_path.read_bytes())['files'].values():
            sources.append(manifest_path.parent / row['snapshot'])
    sources = sorted(set(sources))
    source_hashes = fingerprints(sources)
    g.require(all(source_hashes[path] == expected for path, expected in collection_sources.items()),
              'Collection classification sources changed during projection')
    for source in sources:
        outputs['machinery/' + str(source.relative_to(ROOT)) + '.gz'] = naming_run.compressed(source.read_bytes())
    g.require(fingerprints(frozen_paths()) == frozen, 'Frozen files changed during Run-002')
    manifest = dict(run=RUN, classification='machinery-validation-evidence',
                    governed_baseline='RAD-1.0.10', rad_release_created=None, acceptance='NOT_RECORDED',
                    inputs=fixtures, frozen_files_before=frozen, frozen_files_after=fingerprints(frozen_paths()),
                    release_authority=json.loads(release), source_sha256=source_hashes,
                    files_sha256={key: naming_run.sha(data) for key, data in sorted(outputs.items())})
    outputs['manifest.json'] = naming_run.encoded(manifest)
    return outputs


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--check', action='store_true')
    modes.add_argument('--before-archive', type=Path,
                       help='Explicitly authorised correction: verify this before archive, then replace generated run outputs')
    args = parser.parse_args(argv)
    try:
        outputs = build()
        destination = RUNS / RUN
        run_evidence.write(destination, outputs, check=args.check, before_archive=args.before_archive, repository=ROOT)
        print(json.dumps(dict(status='PASS', mode='CHECK' if args.check else 'CORRECT' if args.before_archive else 'GENERATE', run=RUN,
                              candidate=str((destination / 'candidate.xml').relative_to(ROOT)),
                              navigation=json.loads(outputs['workspace-projection.json'])['summary']), indent=2))
        return 0
    except (OSError, ValueError, KeyError, g.ET.LxmlError) as exc:
        print('UNRESOLVED: ' + str(exc), file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
