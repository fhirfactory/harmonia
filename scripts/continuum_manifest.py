"""Generate/check the root review manifest from canonical continuum elements.

This is a navigation projection, never an element input or architectural authority.
The governed type catalogue supplies native group/type ordering and placement.
"""
import argparse
from collections import Counter, defaultdict
import html
import json
from pathlib import Path
import re
import sys

import architecture_continuum as c


def cell(value):
    """Render source text literally inside a Markdown table, including newlines."""
    if not isinstance(value, str):
        value = json.dumps(value, ensure_ascii=False, sort_keys=True)
    value = html.escape(value, quote=True)
    # Entities prevent Markdown formatting, table delimiters and injected links.
    value = re.sub(r'[\\`*_|\[\]{}]', lambda m: f'&#{ord(m[0])};', value)
    return '<br>'.join(value.splitlines())


def qualifications(metadata):
    parts = [cell('standing.' + key + ': ') + cell(value)
             for key, value in sorted(metadata['standing'].items())
             if key not in ('semantic', 'currentness')]
    parts += [cell('Unresolved ' + key + ': ') + cell(value)
              for key, value in sorted(metadata.get('unresolvedProperties', {}).items())]
    if metadata.get('sourceUnresolved'):
        parts.append('sourceUnresolved: ' + cell(metadata['sourceUnresolved']))
    return '<br>'.join(parts) or 'None recorded'


def render(root=c.ROOT):
    c.validate(root)
    catalogue, elements = c.load(root)
    version = c.read_json(root / 'architecture-release.json')['version']
    by_type = defaultdict(list)
    groups = {}
    for native, profile in catalogue['types'].items():
        group = Path(profile['directory']).parts[0]
        groups.setdefault(group, []).append(native)
    for metadata, _, path in elements.values():
        by_type[metadata['archimateType']].append((metadata, path))
    currentness = Counter(m['standing']['currentness'] for m, _, _ in elements.values())
    specializations = Counter(m['specialization'] for m, _, _ in elements.values() if m.get('specialization'))
    unresolved_names = sum(m['canonicalName'] is None for m, _, _ in elements.values())
    lines = [
        '<!-- Generated by scripts/continuum_manifest.py. Do not edit. -->', '',
        f'# Harmonia Enterprise Architecture continuum — RAD {version}', '',
        '**Generated review/navigation projection for Solution Architect/ARB review.**',
        'Canonical element files remain the architectural source. This manifest is not an',
        'independent source of truth; generation and validation confer no approval.', '',
        f'**{len(elements):,} elements · {len(by_type)} populated native types · '
        f'{len(catalogue["types"])} supported native types · {unresolved_names} unresolved canonicalName values.**', '',
        'Currentness: ' + '; '.join(f'{cell(key)}: {count:,}' for key, count in sorted(currentness.items())) + '.', '',
        'Harmonia specialisations: ' + ('; '.join(f'{cell(key)}: {count:,}' for key, count in sorted(specializations.items())) or 'None') + '.', '',
        'Layer/aspect groups and native type order follow the governed',
        '[type catalogue](../governance/continuum/type-catalogue.json). Rows within each',
        'native type sort by displayName (case-insensitive), then exact displayName and',
        'canonicalId as tie-breakers. Specialisations stay under their native type.',
        'Zero counts identify supported types with no current population.', '',
        'Standing and currentness are independent source values. Unresolved names are',
        'shown explicitly; additional standing qualifications and recorded unresolved',
        'properties appear in the last column. “None recorded” describes that metadata',
        'only; consult the linked canonical file for full content and provenance.',
        'Canonical element paths are relative to this manifest.', '',
        'Regenerate from the repository root with `python3 scripts/continuum_manifest.py`;',
        'verify without writing with `python3 scripts/continuum_manifest.py --check`.', '',
        '## Layer/aspect navigation', '',
        '| Layer/aspect | Elements | Populated / supported native types |',
        '| --- | ---: | ---: |',
    ]
    for group, types in groups.items():
        count = sum(len(by_type.get(native, [])) for native in types)
        populated = sum(bool(by_type.get(native)) for native in types)
        lines.append(f'| [{group.replace("-", " ").title()}](#layer-{group}) | {count:,} | {populated} / {len(types)} |')
    for group, types in groups.items():
        lines += ['', f'<a id="layer-{group}"></a>', f'## {group.replace("-", " ").title()}', '',
                  '| ArchiMate native type | Elements |', '| --- | ---: |']
        for native in types:
            rows = by_type.get(native, [])
            label = f'[{native}](#type-{native.lower()})' if rows else native
            lines.append(f'| {label} | {len(rows):,} |')
        for native in types:
            rows = by_type.get(native, [])
            if not rows:
                continue
            lines += ['', f'<a id="type-{native.lower()}"></a>', f'### {native}', '',
                      '| displayName | ArchiMate native type | Harmonia specialisation | Standing / currentness | canonicalName | Canonical ID | Canonical element path | Qualifications / unresolved values |',
                      '| --- | --- | --- | --- | --- | --- | --- | --- |']
            for m, path in sorted(rows, key=lambda row: (row[0]['displayName'].casefold(), row[0]['displayName'], row[0]['canonicalId'])):
                relative = path.relative_to(root / c.CONTINUUM).as_posix()
                values = [cell(m['displayName']), cell(native), cell(m.get('specialization') or '—'),
                          'Semantic: ' + cell(m['standing']['semantic']) + '<br>Currentness: ' + cell(m['standing']['currentness']),
                          cell(m['canonicalName']) if m['canonicalName'] is not None else '**Unresolved**',
                          cell(m['canonicalId']), f'[{cell(relative)}]({relative})', qualifications(m)]
                lines.append('| ' + ' | '.join(values) + ' |')
    return ('\n'.join(lines) + '\n').encode('utf-8')


def publish(root=c.ROOT, *, check=False):
    content = render(root)
    path = root / c.MANIFEST
    if check:
        c.require(path.exists() and path.read_bytes() == content, 'Missing/stale continuum manifest: ' + str(path))
    else:
        path.write_bytes(content)
    return {'status': 'PASS', 'manifest': c.MANIFEST.as_posix(), 'check': check, 'sha256': c.sha(content)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=c.ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        print(json.dumps(publish(args.root, check=args.check)))
        return 0
    except (c.ContinuumError, ValueError, KeyError, OSError) as error:
        print('FAIL: ' + str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
